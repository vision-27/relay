import argparse
import sys

from . import client, mcp, server, worker, onboarding


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description="Relay — transfer the understanding behind your code")
    commands = parser.add_subparsers(dest="command")
    from . import managed_live, managed_tools
    managed = commands.add_parser('live', help='Start a NEW managed Codex/Claude working session with live coordination')
    managed.add_argument('--repo', help='Suggested repository; always confirmed for this start')
    managed.add_argument('--url', help='Team hub URL; reuses saved browser workspace identity when available')
    managed.add_argument('--project')
    managed.add_argument('--agent', choices=['codex', 'claude'])
    managed.add_argument('--token-file')
    managed.set_defaults(func=managed_live.launch)
    team = commands.add_parser('team', help='NEW agents: automatically plan and share work on an approved team goal')
    team.add_argument('--repo')
    team.add_argument('--url')
    team.add_argument('--project')
    team.add_argument('--agent', choices=['codex', 'claude'])
    team.add_argument('--token-file')
    team.add_argument('--goal', help='Join an existing shared goal by ID or title')
    team.add_argument('--manual', action='store_true', help='Skip automation setup; integrate and test yourself')
    team.set_defaults(func=managed_live.launch, team=True)
    release = commands.add_parser('live-release', help='Explicitly release a stopped managed run after you reconcile its code')
    release.add_argument('--run', required=True, help='Private run record printed by live')
    release.set_defaults(func=managed_live.release)
    managed_mcp = commands.add_parser('managed-mcp', help=argparse.SUPPRESS)
    managed_mcp.add_argument('--config', required=True)
    managed_mcp.set_defaults(func=managed_tools.serve)
    from . import companion
    from . import lifecycle
    for name, function in [('background', lifecycle.background), ('supervise', lifecycle.supervise), ('startup', lifecycle.startup)]:
        service = commands.add_parser(name, help='Manage quiet background operation' if name != 'supervise' else argparse.SUPPRESS)
        service.add_argument('--kind', choices=['desktop', 'hub'], default='desktop')
        service.add_argument('--data', required=True)
        if name == 'startup':
            choice = service.add_mutually_exclusive_group(required=True)
            choice.add_argument('--enable', action='store_true')
            choice.add_argument('--disable', dest='enable', action='store_false')
        service.set_defaults(func=function)
    parser.set_defaults(func=companion.launch, url=None)
    gui = commands.add_parser('gui', help='Open the Relay app in your browser; sync in the background')
    gui.add_argument('--url', help='Default workspace address')
    gui.add_argument('--data', help=argparse.SUPPRESS)
    gui.set_defaults(func=companion.launch)
    desktop = commands.add_parser('desktop', help=argparse.SUPPRESS)
    desktop.add_argument('--url')
    desktop.add_argument('--data', required=True)
    desktop.add_argument('--current')
    desktop.set_defaults(func=companion.desktop)
    start=commands.add_parser('start',help='Guided setup: pick a session and start syncing')
    start.add_argument('--url',help='Workspace address; defaults to the last joined workspace, then localhost')
    start.add_argument('--project')
    start.add_argument('--repo', help='Suggest a folder for this start only; its Git root is always confirmed interactively')
    start.add_argument('--token-file')
    start.add_argument('--setup-only',action='store_true',help='Save the connection without starting the watcher')
    start.set_defaults(func=onboarding.start)
    hub = commands.add_parser("hub", help="Run the shared workspace")
    hub.add_argument("--host", default="127.0.0.1")
    hub.add_argument("--port", type=int, default=7331)
    hub.add_argument("--data", default=".relay/hub")
    hub.add_argument("--public-origin", help="Exact external origin for a private network or TLS reverse proxy")
    hub.set_defaults(func=server.serve)
    connect = commands.add_parser("connect", help="Register a local agent session")
    connect.add_argument("--url", default="http://127.0.0.1:7331")
    connect.add_argument("--project", required=True)
    connect.add_argument("--name", required=True)
    connect.add_argument("--repo", required=True)
    connect.add_argument("--config", default=".relay/connector.json")
    connect.add_argument("--token-file")
    connect.add_argument('--agent',choices=['codex','claude'])
    connect.add_argument('--source-session')
    connect.add_argument('--source-file',help='Explicit Claude session transcript path')
    connect.add_argument('--share-session',action='store_true',help='Enable ongoing selected-session sharing and explanation forks')
    connect.add_argument('--max-calls-per-hour',type=int,default=12)
    connect.set_defaults(func=client.connect)
    publish = commands.add_parser("publish", help="Preview or publish an explicitly selected checkpoint JSON")
    publish.add_argument("--config", default=".relay/connector.json")
    publish.add_argument("--file", required=True)
    publish.add_argument("--share", action="store_true")
    publish.set_defaults(func=client.publish)
    agent = commands.add_parser("mcp", help="Run the local agent's MCP stdio connector")
    agent.add_argument("--config", default=".relay/connector.json")
    agent.set_defaults(func=mcp.run)
    live=commands.add_parser('watch',help='Continuously sync a connected source session and answer clarifications')
    live.add_argument('--config',default='.relay/connector.json')
    live.set_defaults(func=worker.watch)
    discovery=commands.add_parser('sessions',help='List source session metadata for one repository')
    discovery.add_argument('--agent',choices=['codex','claude'],required=True)
    discovery.add_argument('--repo',required=True)
    discovery.set_defaults(func=client.sessions)
    args = parser.parse_args()
    try:
        args.func(args)
    except (KeyboardInterrupt, EOFError):
        print('\nStopped. Run relay-workspace live for a new managed session.' if args.command == 'live'
              else '\nStopped. Run python -m relay start when you want to reconnect.')
    except (ValueError, OSError) as exc:
        print(f"Relay: {exc}", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
